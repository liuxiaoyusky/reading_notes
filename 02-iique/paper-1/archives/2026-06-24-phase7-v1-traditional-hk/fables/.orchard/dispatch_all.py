#!/usr/bin/env python3
"""Dispatch implementer subagents for every fab in this book.

Usage:
    python3 dispatch_all.py [--chapter 01-風險及保險] [--limit 5] [--concurrency 4]

Reads manifest.json, picks fabs with status == pending, dispatches one Claude
subagent per fab to: read source + cast + world, write the fable, self-review
(spec + quality), then record the result via orchard.py.

The driver itself is intentionally tiny — it only handles batch / concurrency.
All review and recording happens inside the subagent (so the subagent owns its
verdict and orchard.py record calls).
"""

